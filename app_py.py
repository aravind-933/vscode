import streamlit as st
from dotenv import load_dotenv

load_dotenv()

from rag_engine import (  # noqa: E402
    build_vector_store,
    extract_documents,
    generate_answer,
    retrieve_documents,
)


st.set_page_config(
    page_title="RAG Document Assistant",
    page_icon="📚",
    layout="wide",
)

st.title("📚 RAG Document Assistant")
st.write(
    "Upload documents, create a searchable knowledge base, "
    "and ask questions about their contents."
)

if "vector_store" not in st.session_state:
    st.session_state.vector_store = None

if "chunk_count" not in st.session_state:
    st.session_state.chunk_count = 0


with st.sidebar:
    st.header("Knowledge Base")

    uploaded_files = st.file_uploader(
        "Upload PDF or TXT files",
        type=["pdf", "txt"],
        accept_multiple_files=True,
    )

    process_button = st.button(
        "Process documents",
        type="primary",
        use_container_width=True,
    )

    if process_button:
        if not uploaded_files:
            st.warning("Upload at least one document.")
        else:
            try:
                with st.spinner("Reading and indexing documents..."):
                    documents = extract_documents(uploaded_files)

                    if not documents:
                        st.error(
                            "No readable text was found in the documents."
                        )
                    else:
                        vector_store, chunks = build_vector_store(documents)

                        st.session_state.vector_store = vector_store
                        st.session_state.chunk_count = len(chunks)

                        st.success(
                            f"Knowledge base ready: {len(chunks)} chunks."
                        )

            except Exception as error:
                st.error(f"Document processing failed: {error}")

    if st.session_state.vector_store is not None:
        st.info(
            f"Indexed chunks: {st.session_state.chunk_count}"
        )


st.subheader("Ask a question")

question = st.text_input(
    "Question",
    placeholder="What is the main idea of the document?",
)

ask_button = st.button("Get answer", type="primary")

if ask_button:
    if st.session_state.vector_store is None:
        st.warning("Process the documents before asking a question.")

    elif not question.strip():
        st.warning("Enter a question.")

    else:
        try:
            with st.spinner("Searching the documents..."):
                retrieved_documents = retrieve_documents(
                    vector_store=st.session_state.vector_store,
                    question=question,
                    number_of_chunks=4,
                )

                answer = generate_answer(
                    question=question,
                    retrieved_documents=retrieved_documents,
                )

            st.subheader("Answer")
            st.write(answer)

            with st.expander("Retrieved evidence"):
                for index, document in enumerate(
                    retrieved_documents,
                    start=1,
                ):
                    source = document.metadata.get(
                        "source",
                        "Unknown",
                    )
                    page = document.metadata.get(
                        "page",
                        "Unknown",
                    )

                    st.markdown(
                        f"**Chunk {index} — {source}, page {page}**"
                    )
                    st.write(document.page_content)
                    st.divider()

        except Exception as error:
            st.error(f"Question answering failed: {error}")