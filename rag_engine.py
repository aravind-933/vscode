import os

from langchain_community.vectorstores import FAISS
from langchain_core.documents import Document
from langchain_groq import ChatGroq
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter
from pypdf import PdfReader


EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"


def extract_documents(uploaded_files):
    """Extract text from uploaded PDF and TXT files."""

    documents = []

    for uploaded_file in uploaded_files:
        filename = uploaded_file.name
        extension = filename.lower().split(".")[-1]

        if extension == "pdf":
            reader = PdfReader(uploaded_file)

            for page_number, page in enumerate(reader.pages, start=1):
                text = page.extract_text() or ""

                if text.strip():
                    documents.append(
                        Document(
                            page_content=text,
                            metadata={
                                "source": filename,
                                "page": page_number,
                            },
                        )
                    )

        elif extension == "txt":
            text = uploaded_file.getvalue().decode(
                "utf-8",
                errors="ignore",
            )

            if text.strip():
                documents.append(
                    Document(
                        page_content=text,
                        metadata={
                            "source": filename,
                            "page": 1,
                        },
                    )
                )

    return documents


def build_vector_store(documents):
    """Split documents, create embeddings, and store them in FAISS."""

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=800,
        chunk_overlap=120,
        separators=["\n\n", "\n", ". ", " ", ""],
    )

    chunks = text_splitter.split_documents(documents)

    embeddings = HuggingFaceEmbeddings(
        model_name=EMBEDDING_MODEL
    )

    vector_store = FAISS.from_documents(
        documents=chunks,
        embedding=embeddings,
    )

    return vector_store, chunks


def retrieve_documents(vector_store, question, number_of_chunks=4):
    """Retrieve chunks most relevant to the student's question."""

    return vector_store.similarity_search(
        query=question,
        k=number_of_chunks,
    )


def generate_answer(question, retrieved_documents):
    """Generate an answer using only the retrieved context."""

    api_key = os.getenv("GROQ_API_KEY")
    model_name = os.getenv(
        "GROQ_MODEL",
        "openai/gpt-oss-20b",
    )

    if not api_key:
        raise ValueError("GROQ_API_KEY was not found in the .env file.")

    context_parts = []

    for index, document in enumerate(retrieved_documents, start=1):
        source = document.metadata.get("source", "Unknown")
        page = document.metadata.get("page", "Unknown")

        context_parts.append(
            f"""Context {index}
Source: {source}
Page: {page}
Text:
{document.page_content}
"""
        )

    context = "\n\n".join(context_parts)

    prompt = f"""
You are a document question-answering assistant.

Answer the question using only the context provided below.

Rules:
1. Do not use outside knowledge.
2. If the answer is not in the context, say:
   "I could not find that information in the uploaded documents."
3. Give a clear and concise answer.
4. Mention the source filename and page number when possible.

Context:
{context}

Question:
{question}

Answer:
print("DEBUG MODEL:", repr(model_name))
"""

    model = ChatGroq(
        api_key=api_key,
        model=model_name,
        temperature=0,
    )

    response = model.invoke(prompt)

    return response.content